#!/usr/bin/env python3
"""Writes the FAQ accordion of the website (between the FAQ markers in site/index.html) from docs/faq.md,
so the two never drift apart. Usage: python3 deck/tools/make-site-faq.py"""
import html, os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
md = open(os.path.join(ROOT, 'docs', 'faq.md'), encoding='utf-8').read()

def inline(t):
    t = html.escape(t, quote=False)
    t = re.sub(r'`([^`]+)`', r'<code>\1</code>', t)
    t = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', t)
    def link(m):
        href = m.group(2)
        if not href.startswith('http'):
            href = 'https://github.com/Nokoding/visor-launcher/blob/main/docs/' + href.replace('../', '') if not href.startswith('../') else 'https://github.com/Nokoding/visor-launcher/blob/main/' + href[3:]
        return '<a href="%s">%s</a>' % (href, m.group(1))
    return re.sub(r'\[([^\]]+)\]\(([^)]+)\)', link, t)

items = []
for block in re.split(r'\n## ', md)[1:]:
    q, _, rest = block.partition('\n')
    paras = [p.strip() for p in rest.strip().split('\n\n') if p.strip()]
    body = ''.join('<p>%s</p>' % inline(p.replace('\n', ' ')) for p in paras)
    items.append('<details><summary>%s</summary>%s</details>' % (inline(q.strip()), body))
out = '<!-- FAQ:START (generated by deck/tools/make-site-faq.py from docs/faq.md) -->\n' + '\n'.join(items) + '\n<!-- FAQ:END -->'
p = os.path.join(ROOT, 'site', 'index.html')
s = open(p, encoding='utf-8').read()
s = re.sub(r'<!-- FAQ:START.*?<!-- FAQ:END -->', lambda m: out, s, flags=re.S)
open(p, 'w', encoding='utf-8').write(s)
print('faq items:', len(items))
